// GrepToolMessageItem 是 消息 item 那 represents grep 工具调用.
type GrepToolMessageItem struct {
	*baseToolMessageItem
}

var _ ToolMessageItem = (*GrepToolMessageItem)(nil)

// NewGrepToolMessageItem creates a new [GrepToolMessageItem].
func NewGrepToolMessageItem(
	sty *styles.Styles,
	toolCall message.ToolCall,
	result *message.ToolResult,
	canceled bool,
) ToolMessageItem {
	return newBaseToolMessageItem(sty, toolCall, result, &GrepToolRenderContext{}, canceled)
}

// GrepToolRenderContext renders grep 工具 messages.
type GrepToolRenderContext struct{}

// partialGrepParams recovers grep parameters 那 already finished
// streaming 从 partial 工具调用 input.
func partialGrepParams(input string) tools.GrepParams {
	fields := partialJSONFields(input)
	var params tools.GrepParams
	params.Pattern, _ = fields["pattern"].(string)
	params.Path, _ = fields["path"].(string)
	params.Include, _ = fields["include"].(string)
	params.LiteralText, _ = fields["literal_text"].(bool)
	return params
}

// RenderTool implements the [ToolRenderer] interface.
func (g *GrepToolRenderContext) RenderTool(sty *styles.Styles, width int, opts *ToolRenderOpts) string {
	cappedWidth := cappedMessageWidth(width)
	var params tools.GrepParams
	if err := json.Unmarshal([]byte(opts.ToolCall.Input), &params); err != nil {
		if !opts.IsStreamingInput() {
			return toolErrorContent(sty, &message.ToolResult{Content: "Invalid parameters"}, cappedWidth)
		}
		// While 工具调用 input 是 still streaming it 是 incomplete
		// 和 不 valid JSON yet. Show whatever fields already arrived,
		// 或 plain spinner until pattern 是 完成.
		params = partialGrepParams(opts.ToolCall.Input)
		if params.Pattern == "" {
			return pendingTool(sty, "Grep", opts.Anim, opts.Compact)
		}
	}

	toolParams := []string{params.Pattern}
	if params.Path != "" {
		toolParams = append(toolParams, "path", params.Path)
	}
	if params.Include != "" {
		toolParams = append(toolParams, "include", params.Include)
	}
	if params.LiteralText {
		toolParams = append(toolParams, "literal", "true")
	}

	if opts.IsStreamingInput() {
		header := toolHeader(sty, opts.Status, "Grep", cappedWidth, opts, toolParams...)
		var animView string
		if opts.Anim != nil {
			animView = opts.Anim.Render()
		}
		return header + " " + animView
	}

	header := toolHeader(sty, opts.Status, "Grep", cappedWidth, opts, toolParams...)
	if opts.Compact {
		return header
	}

	if earlyState, ok := toolEarlyStateContent(sty, opts, cappedWidth); ok {
		return joinToolParts(header, earlyState)
	}

	if opts.HasEmptyResult() {
		return header
	}

	bodyWidth := cappedWidth - toolBodyLeftPaddingTotal
	body := sty.Tool.Body.Render(toolOutputPlainContent(sty, opts.Result.Content, bodyWidth, opts.ExpandedContent))
	return joinToolParts(header, body)
}

